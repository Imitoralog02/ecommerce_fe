  static List<String> districtsForCity(String city) {
    final map = administrativeUnits[city];
    if (map == null) return const [];
    return map.keys.toList();
  }

  static List<String> wardsForDistrict(String city, String district) {
    final map = administrativeUnits[city];
    if (map == null) return const [];
    return map[district] ?? const [];
